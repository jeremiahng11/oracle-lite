# PlatformIO pre-build script: gzip web/app.html (the Web Companion app) into
# oracle_lite/src/app/web_app_gz.h so the firmware can serve it as-is.
import gzip
import hashlib
import os

Import("env")  # noqa: F821  (provided by PlatformIO)

project = env.subst("$PROJECT_DIR")  # noqa: F821
source = os.path.join(project, "web", "app.html")
target = os.path.join(project, "oracle_lite", "src", "app", "web_app_gz.h")

if os.path.exists(source):
    with open(source, "rb") as f:
        html = f.read()
else:
    html = b"<!doctype html><title>Oracle Lite</title><p>web/app.html is missing from this build.</p>"

packed = gzip.compress(html, compresslevel=9, mtime=0)
etag = hashlib.sha1(packed).hexdigest()[:16]
lines = ["// Generated by scripts/web_embed.py from web/app.html. Do not edit.",
         "#pragma once", "#include <stdint.h>",
         'static const char kWebAppEtag[] = "%s";' % etag,
         "static const uint8_t kWebAppGz[%d] = {" % len(packed)]
for i in range(0, len(packed), 24):
    lines.append("  " + ",".join(str(b) for b in packed[i:i + 24]) + ",")
lines.append("};")
text = "\n".join(lines) + "\n"
old = open(target).read() if os.path.exists(target) else ""
if old != text:
    with open(target, "w") as f:
        f.write(text)
print("Web Companion app: %d bytes, %d gzipped" % (len(html), len(packed)))
